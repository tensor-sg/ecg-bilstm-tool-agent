"""Evaluate the trained ECG LSTM on held-out MIT-BIH patients and write a report.

Usage:
    python scripts/evaluate_model.py                 # DS2 (inter-patient test set)
    python scripts/evaluate_model.py --records 100 233

Writes reports/evaluation.json and reports/evaluation.md.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.ecg import mitbih  # noqa: E402
from app.ecg.classifier import ECGClassifier  # noqa: E402
from app.ecg.evaluation import evaluate_annotated, evaluate_end_to_end  # noqa: E402


def _ci(v: list[float]) -> str:
    return f"[{v[0]:.3f}–{v[1]:.3f}]"


def metrics_table(m: dict) -> str:
    ci = m["ci95"]["per_class"]
    lines = [
        "| Class | Support | Sensitivity (95% CI) | PPV (95% CI) | Specificity | F1 |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for c, v in m["per_class"].items():
        lines.append(
            f"| {c} | {v['support']:,} | {v['sensitivity']:.3f} {_ci(ci[c]['sensitivity'])} | "
            f"{v['ppv']:.3f} {_ci(ci[c]['ppv'])} | {v['specificity']:.3f} | {v['f1']:.3f} |"
        )
    return "\n".join(lines)


def headline(m: dict) -> str:
    ci = m["ci95"]
    return (
        f"Accuracy **{m['accuracy']:.3f}** {_ci(ci['accuracy'])} · macro-F1 **{m['macro_f1']:.3f}** {_ci(ci['macro_f1'])} · "
        f"balanced accuracy **{m['balanced_accuracy']:.3f}** {_ci(ci['balanced_accuracy'])} · {m['n_beats']:,} beats"
    )


def confusion_table(m: dict, classes: list[str]) -> str:
    lines = ["| true \\ pred | " + " | ".join(classes) + " |", "|---|" + "---:|" * len(classes)]
    for c, row in zip(classes, m["confusion_matrix"]):
        lines.append(f"| **{c}** | " + " | ".join(f"{v:,}" for v in row) + " |")
    return "\n".join(lines)


def to_markdown(report: dict) -> str:
    a, e, classes = report["annotated"], report["end_to_end"], report["classes"]
    det = e["detection"]
    cls = "/".join(classes)
    per_rec = [f"| Record | Beats | Accuracy | True ({cls}) | Predicted ({cls}) |", "|---|---:|---:|---|---|"]
    excluded = a.get("excluded_classes_predicted_as", {})
    ex_lines = [f"| True label | Beats | " + " | ".join(f"→ {c}" for c in classes) + " |", "|---|---:|" + "---:|" * len(classes)]
    for label, dist in excluded.items():
        ex_lines.append(f"| {label} | {sum(dist.values()):,} | " + " | ".join(f"{dist[c]:,}" for c in classes) + " |")
    ex_section = "\n".join(ex_lines) if excluded else "None."
    for rec, v in a["per_record"].items():
        t = "/".join(str(v["true_counts"].get(c, 0)) for c in classes)
        p = "/".join(str(v["pred_counts"].get(c, 0)) for c in classes)
        per_rec.append(f"| {rec} | {v['n_beats']:,} | {v['accuracy']:.3f} | {t} | {p} |")
    return f"""# ECG LSTM evaluation report

Generated by `scripts/evaluate_model.py` on {report['generated_at']}.
Model: `{report['model_path']}` · trained with split `{report['train_split']}` · classes {', '.join(classes)}
Test records ({len(report['records'])}): {', '.join(report['records'])}

## 1. Classifier performance at annotated R-peaks

{headline(a)}

95% confidence intervals: patient-level bootstrap ({a['ci95']['n_boot']} resamples of test records).

{metrics_table(a)}

{confusion_table(a, classes)}

## 2. End-to-end pipeline (own R-peak detector, as used by the API)

R-peak detection: sensitivity **{det['sensitivity']:.4f}**, PPV **{det['ppv']:.4f}**
({det['matched']:,} of {det['reference_beats']:,} annotated beats matched within ±{det['tolerance_ms']} ms; {det['detected_beats']:,} detections)

Classification of matched beats: {headline(e)}

{metrics_table(e)}

{confusion_table(e, classes)}

## 3. Beats of classes the model was not trained on

These beats are not part of the metrics above; the table shows what the model calls them.

{ex_section}

## 4. Per-record results (annotated R-peaks)

{chr(10).join(per_rec)}
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--records", nargs="*", default=mitbih.DS2)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data" / "mitdb")
    parser.add_argument("--model", type=Path, default=ROOT / "models" / "ecg_lstm.keras")
    parser.add_argument("--meta", type=Path, default=ROOT / "models" / "ecg_lstm_meta.json")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "reports")
    args = parser.parse_args()

    mitbih.download(args.data_dir)
    clf = ECGClassifier(args.model, args.meta)

    t0 = time.time()
    report = {
        "generated_at": time.strftime("%Y-%m-%d %H:%M"),
        "model_path": str(args.model.relative_to(ROOT) if args.model.is_relative_to(ROOT) else args.model),
        "train_split": clf.meta.get("split"),
        "classes": clf.classes,
        "records": args.records,
        "annotated": evaluate_annotated(clf, args.data_dir, args.records),
        "end_to_end": evaluate_end_to_end(clf, args.data_dir, args.records),
    }
    report["eval_seconds"] = round(time.time() - t0, 1)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "evaluation.json").write_text(json.dumps(report, indent=2))
    (args.out_dir / "evaluation.md").write_text(to_markdown(report))

    a, e = report["annotated"], report["end_to_end"]
    print(f"annotated : acc={a['accuracy']:.3f} macroF1={a['macro_f1']:.3f} " + " ".join(f"{c}:Se={v['sensitivity']:.2f}/PPV={v['ppv']:.2f}" for c, v in a["per_class"].items()))
    print(f"end-to-end: acc={e['accuracy']:.3f} macroF1={e['macro_f1']:.3f} detSe={e['detection']['sensitivity']:.4f} detPPV={e['detection']['ppv']:.4f}")
    print(f"wrote {args.out_dir / 'evaluation.md'} ({report['eval_seconds']} s)")


if __name__ == "__main__":
    main()
